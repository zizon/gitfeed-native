// First-run scaffolding for a data root that has nothing in it yet.
//
// The plugin package is code only, but its CI job must run without a checkout
// of this package, so `gitfeed init` (and `gitfeed ci` on an existing root)
// also writes a stand-alone bundle of the CLI and the workflow that runs it
// into the data repository. The data it reads — subscriptions, config, fetched
// items, read/star state — belongs to that same usually-private repository.
// When a root has never been created, this writes a minimal but complete
// starting point so the reader mounts with an empty inbox instead of an error,
// and so `git init` in that directory immediately has the merge rules and
// ignore list it needs.

import fs from 'node:fs'
import path from 'node:path'
import { pathsFor } from './settings.js'

/** Entries that do not make a directory "someone else's data". */
const IGNORED_ENTRIES = new Set(['.git', '.DS_Store', '.local'])

const FEEDS = `${JSON.stringify({
  '$comment': 'Subscription list. Edit by hand, use Add feed in the reader, or run `gitfeed import-opml`; then Sync.',
  feeds: [],
}, null, 2)}\n`

const CONFIG = `${JSON.stringify({
  fetch: { concurrency: 6, timeoutMs: 25000, keepMonths: 6, maxSummaryChars: 0 },
  reader: { hideEmptyFeeds: true, markReadOnScroll: true, groupBy: 'none' },
}, null, 2)}\n`

const GITATTRIBUTES = [
  '# Read/star state is append-only (one id per line). Union merge means two',
  '# machines marking different items read can never conflict.',
  'data/read.ndjson merge=union',
  'data/starred.ndjson merge=union',
  '# Item shards are appended to by fetches (local or CI); union keeps a',
  '# racing push from colliding.',
  'data/items/*.ndjson merge=union',
  '',
].join('\n')

const GITIGNORE = [
  '# local refresh cache (never committed)',
  '.local/',
  '.DS_Store',
  '*.log',
  '.tmp/',
  'node_modules/',
  '',
].join('\n')

/** Where the generated CI files live inside a data root. */
const CI_ENTRY = '.gitfeed/gitfeed.mjs'
const CI_WORKFLOW = '.github/workflows/fetch.yml'

const CI_WORKFLOW_TEXT = [
  '# Generated by gitfeed-native. `gitfeed ci` rewrites this file and',
  '# .gitfeed/gitfeed.mjs; commit both after upgrading the plugin.',
  'name: fetch',
  '',
  'on:',
  '  schedule:',
  '    - cron: "1,31 * * * *"',
  '  workflow_dispatch:',
  '',
  'permissions:',
  '  contents: write',
  '',
  'concurrency:',
  '  group: fetch',
  '  cancel-in-progress: false',
  '',
  'jobs:',
  '  fetch:',
  '    runs-on: ubuntu-latest',
  '    steps:',
  '      - uses: actions/checkout@v5',
  '',
  '      - uses: actions/setup-node@v5',
  '        with:',
  '          node-version: 22',
  '',
  '      # The fetcher is committed with the data, so the job needs no access',
  '      # to any code repository and no token beyond its own GITHUB_TOKEN.',
  '      - name: Fetch feeds',
  '        run: node .gitfeed/gitfeed.mjs fetch',
  '',
  '      - name: Commit new items',
  '        run: |',
  '          git config user.name "gitfeed"',
  '          git config user.email "gitfeed@users.noreply.github.com"',
  '          git add data',
  '          if git diff --staged --quiet; then',
  '            echo "no new items"',
  '            exit 0',
  '          fi',
  '          git commit -m "feed: $(date -u +%Y-%m-%dT%H:%MZ)"',
  '          # Rebase in case a local machine pushed read state meanwhile.',
  '          git pull --rebase --autostash',
  '          git push',
  '',
].join('\n')

/** Relative path -> content for a starter data root. */
const STARTER_FILES: Array<[string, string]> = [
  ['feeds.json', FEEDS],
  ['config.json', CONFIG],
  ['data/meta.json', '{}\n'],
  ['data/read.ndjson', ''],
  ['data/starred.ndjson', ''],
  ['.gitattributes', GITATTRIBUTES],
  ['.gitignore', GITIGNORE],
]

export interface ScaffoldResult {
  seeded: boolean
  reason: 'seeded' | 'present' | 'not-empty'
}

function isPristine(dir: string): boolean {
  try {
    return fs.readdirSync(dir).every(function (name) { return IGNORED_ENTRIES.has(name) })
  } catch {
    return false
  }
}

/**
 * The CLI bundle this package ships. It is read from `lib/gitfeed.mjs` when
 * the CLI runs from the built tree, and from the bundle itself when the
 * command is the copy inside a data repository.
 * @returns the bundle source.
 */
function cliBundleSource(): string {
  const candidates = [
    new URL('./gitfeed.mjs', import.meta.url),
    new URL('../gitfeed.mjs', import.meta.url),
  ]
  for (const candidate of candidates) {
    try {
      return fs.readFileSync(candidate, 'utf8')
    } catch {
      // try the next location
    }
  }
  throw new Error('the gitfeed CLI bundle is missing; run `pnpm build` in the gitfeed-native checkout')
}

/**
 * The files that make a data root self-contained for CI: the stand-alone CLI
 * bundle and the workflow that runs it.
 * @returns relative path / content pairs.
 */
export function ciFiles(): Array<[string, string]> {
  return [
    [CI_ENTRY, cliBundleSource()],
    [CI_WORKFLOW, CI_WORKFLOW_TEXT],
  ]
}

function writeIfMissing(file: string, text: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  try {
    fs.writeFileSync(file, text, { flag: 'wx' })
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'EEXIST') throw err
  }
}

/**
 * Create the starter data root in `root` when it has no reader yet.
 *
 * A missing root is created; an existing root is filled only when it holds
 * nothing but a `.git`, `.local`, or `.DS_Store`. A root that already has
 * `feeds.json` is left untouched.
 * @param root absolute data root.
 * @returns what happened, for the caller's log line.
 */
export function scaffoldData(root: string): ScaffoldResult {
  const resolved = path.resolve(root)
  if (fs.existsSync(pathsFor(resolved).feeds)) return { seeded: false, reason: 'present' }
  if (fs.existsSync(resolved) && !isPristine(resolved)) return { seeded: false, reason: 'not-empty' }
  for (const [relative, text] of STARTER_FILES) {
    writeIfMissing(path.join(resolved, relative), text)
  }
  for (const [relative, text] of ciFiles()) {
    writeIfMissing(path.join(resolved, relative), text)
  }
  return { seeded: true, reason: 'seeded' }
}

export interface CiResult {
  root: string
  files: string[]
}

/**
 * Write, or refresh, the CI files in an existing data root.
 * @param root absolute data root.
 * @returns the root and the files written.
 */
export function installCi(root: string): CiResult {
  const resolved = path.resolve(root)
  if (!fs.existsSync(pathsFor(resolved).feeds)) {
    throw new Error(`${resolved} is not a gitfeed data root (no feeds.json); run \`gitfeed init\` first`)
  }
  const files: string[] = []
  for (const [relative, text] of ciFiles()) {
    const target = path.join(resolved, relative)
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, text)
    files.push(relative)
  }
  return { root: resolved, files: files }
}

/**
 * The files a starter root contains, for the CLI's confirmation output.
 * @returns relative paths.
 */
export function starterFiles(): string[] {
  const files = STARTER_FILES.map(function (entry) { return entry[0] })
  try {
    for (const [relative] of ciFiles()) files.push(relative)
  } catch {
    // the bundle is missing (an unbuilt checkout); the data files still seed
  }
  return files
}
